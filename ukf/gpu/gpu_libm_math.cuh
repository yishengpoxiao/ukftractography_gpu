UKF_LIBM_FUNCTION double d_libm_madd(double a, double b, double c, int fused) {
  return fused ? fma(a, b, c) : a * b + c;
}
UKF_LIBM_FUNCTION double d_libm_exp(double x, int fused = 1) {
  if (!(fabs(x) < 512))
    return exp(x);
  if (fabs(x) < 0x1p-54)
    return 1 + x;
  double kd = d_libm_madd(0x1.71547652b82fep7, x, 0x1.8p52, fused);
  unsigned long long ki = d_libm_bits(kd);
  kd -= 0x1.8p52;
  double r = d_libm_madd(kd, -0x1.62e42fefa0000p-8, x, fused);
  r = d_libm_madd(kd, -0x1.cf79abc9e3b3ap-47, r, fused);
  int idx = 2 * (ki % 128);
  double tail = d_libm_value(d_libm_exp_table[idx]);
  double scale = d_libm_value(d_libm_exp_table[idx + 1] + (ki << 45));
  double r2 = r * r;
  double t = d_libm_madd(r, 0x1.555555555543cp-3, 0x1.ffffffffffdbdp-2, fused);
  t = d_libm_madd(r2, t, tail + r, fused);
  t = d_libm_madd(
      r2 * r2,
      d_libm_madd(r, 0x1.1111167a4d017p-7, 0x1.55555cf172b91p-5, fused), t,
      fused);
  return d_libm_madd(scale, t, scale, fused);
}
UKF_LIBM_FUNCTION double d_libm_core_cos(double x, double dx, int fused) {
  if (x < 0)
    dx = -dx;
  double u = 0x1.8p45 + fabs(x);
  int k = (unsigned int)d_libm_bits(u) * 4;
  x = (fabs(x) - (u - 0x1.8p45)) + dx;
  double xx = x * x;
  double s =
      d_libm_madd(x * xx,
                  d_libm_madd(xx, 8.33333214285722277379541354343671E-03,
                              -1.66666666666664880952546298448555E-01, fused),
                  x, fused);
  double c =
      xx *
      d_libm_madd(xx,
                  d_libm_madd(xx, 1.38888874007937613028114285595617E-03,
                              -4.16666666666664434524222570944589E-02, fused),
                  4.99999999999999999999950396842453E-01, fused);
  double sn = d_libm_value(d_libm_sin_table[k]),
         ssn = d_libm_value(d_libm_sin_table[k + 1]),
         cs = d_libm_value(d_libm_sin_table[k + 2]),
         ccs = d_libm_value(d_libm_sin_table[k + 3]);
  double cor = d_libm_madd(-s, ssn, ccs, fused);
  cor = d_libm_madd(-cs, c, cor, fused);
  cor = d_libm_madd(-sn, s, cor, fused);
  return cs + cor;
}
UKF_LIBM_FUNCTION double d_libm_core_sin(double x, double dx, int fused) {
  if (fabs(x) < .126) {
    double xx = x * x;
    double p =
        d_libm_madd(-0x1.ADDFFC2FCDF59p-26, xx, 0x1.71DE27B9A7ED9p-19, fused);
    p = d_libm_madd(p, xx, -0x1.A01A019DB08B8p-13, fused);
    p = d_libm_madd(p, xx, 0x1.1111111110ECEp-7, fused);
    p = d_libm_madd(p, xx, -0x1.5555555555555p-3, fused);
    double t = d_libm_madd(p, x, -.5 * dx, fused);
    t = d_libm_madd(t, xx, dx, fused);
    return x + t;
  }
  double old = x;
  if (x <= 0)
    dx = -dx;
  double u = 0x1.8p45 + fabs(x);
  int k = (unsigned int)d_libm_bits(u) * 4;
  x = fabs(x) - (u - 0x1.8p45);
  double xx = x * x;
  double s =
      x +
      d_libm_madd(x * xx,
                  d_libm_madd(xx, 8.33333214285722277379541354343671E-03,
                              -1.66666666666664880952546298448555E-01, fused),
                  dx, fused);
  double c = d_libm_madd(
      x, dx,
      xx * d_libm_madd(xx,
                       d_libm_madd(xx, 1.38888874007937613028114285595617E-03,
                                   -4.16666666666664434524222570944589E-02,
                                   fused),
                       4.99999999999999999999950396842453E-01, fused),
      fused);
  double sn = d_libm_value(d_libm_sin_table[k]),
         ssn = d_libm_value(d_libm_sin_table[k + 1]),
         cs = d_libm_value(d_libm_sin_table[k + 2]),
         ccs = d_libm_value(d_libm_sin_table[k + 3]);
  double cor = d_libm_madd(s, ccs, ssn, fused);
  cor = d_libm_madd(-sn, c, cor, fused);
  cor = d_libm_madd(cs, s, cor, fused);
  return copysign(sn + cor, old);
}
UKF_LIBM_FUNCTION int d_libm_reduce(double x, double &a, double &da,
                                    int fused) {
  double t = d_libm_madd(x, 0x1.45F306DC9C883p-1, 0x1.8p52, fused),
         xn = t - 0x1.8p52;
  int n = (unsigned int)d_libm_bits(t) & 3;
  double y = d_libm_madd(-xn, 0x1.921FB58000000p0, x, fused);
  y = d_libm_madd(-xn, -0x1.DDE973C000000p-27, y, fused);
  double t2 = d_libm_madd(-xn, -0x1.CB3B398000000p-55, y, fused);
  double db = d_libm_madd(-xn, -0x1.CB3B398000000p-55, y - t2, fused);
  a = d_libm_madd(-xn, -0x1.d747f23e32ed7p-83, t2, fused);
  db += d_libm_madd(-xn, -0x1.d747f23e32ed7p-83, t2 - a, fused);
  da = db;
  return n;
}
UKF_LIBM_FUNCTION void d_libm_sincos(double x, double &s, double &c,
                                     int fused = 1) {
  unsigned int k = d_libm_bits(x) >> 32 & 0x7fffffff;
  double a, da;
  if (k < 0x3e400000) {
    s = x;
    c = 1;
    return;
  }
  if (k < 0x3feb6000) {
    s = d_libm_core_sin(x, 0, fused);
    c = d_libm_core_cos(x, 0, fused);
    return;
  }
  if (k < 0x400368fd) {
    double y = 0x1.921FB54442D18p0 - fabs(x);
    a = y + 0x1.1A62633145C07p-54;
    da = (y - a) + 0x1.1A62633145C07p-54;
    s = copysign(d_libm_core_cos(a, da, fused), x);
    c = d_libm_core_sin(a, da, fused);
    return;
  }
  if (k >= 0x419921fb) {
    s = sin(x);
    c = cos(x);
    return;
  }
  int n = d_libm_reduce(x, a, da, fused);
  if (n == 1 || n == 2) {
    a = -a;
    da = -da;
  }
  s = d_libm_core_sin(a, da, fused);
  c = d_libm_core_cos(a, da, fused);
  if (n & 2)
    c = -c;
  if (n & 1) {
    double t = s;
    s = c;
    c = t;
  }
}

